-- =============================================================
-- VARIABLES DE LA TIENDA - PostgreSQL
-- Base de datos: erp_tienda
--
-- Tabla del ERP que usa el modulo "AJUSTES" del catalogo web para
-- personalizar textos sin tocar codigo. Variables usadas hoy:
--
--   TEXTO_BANNER   -> texto del banner superior (layouts/header2.php)
--   NOMBRE_NEGOCIO -> nombre del negocio en la tienda (header/footer)
--
-- La columna name es CHAR(20): siempre se compara/lee con trim().
-- El CRUD se administra en: /ajustes  (Ajustes_model + Ajustes.php)
--
-- Ejecutar con:
--   SET PGPASSWORD=postgresql
--   psql -U postgres -h localhost -d erp_tienda -f database\tec_variables.sql
-- =============================================================

CREATE TABLE IF NOT EXISTS tec_variables (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id  INTEGER NOT NULL DEFAULT 1,
    name      CHAR(20) DEFAULT NULL,
    dato      VARCHAR(1200) DEFAULT NULL,
    fec_reg   DATE
);

CREATE INDEX IF NOT EXISTS idx_variables_store_id ON tec_variables(store_id);

-- =============================================================
-- VALORES INICIALES
-- Se insertan solo si no existen (la columna name no es unica,
-- por eso la validacion se hace con NOT EXISTS sobre trim(name)).
-- =============================================================

INSERT INTO tec_variables (store_id, name, dato, fec_reg)
SELECT 1, 'TEXTO_BANNER', 'DESCUENTOS POR TEMPORADA...', CURRENT_DATE
WHERE NOT EXISTS (
    SELECT 1 FROM tec_variables WHERE upper(trim(name)) = 'TEXTO_BANNER'
);

INSERT INTO tec_variables (store_id, name, dato, fec_reg)
SELECT 1, 'NOMBRE_NEGOCIO', 'BELLAROSSE', CURRENT_DATE
WHERE NOT EXISTS (
    SELECT 1 FROM tec_variables WHERE upper(trim(name)) = 'NOMBRE_NEGOCIO'
);

